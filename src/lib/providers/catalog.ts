import type {
  CatalogModel,
  ChatFeature,
  FreeTier,
  ProviderCatalogEntry,
} from '@/types/core';

/**
 * Prices are list prices in USD per 1M tokens, as published by each provider.
 *
 * Image and rerank endpoints are not token-billed upstream, so they are encoded
 * with the convention "one image / one search unit == 1,000 tokens". A $0.04
 * image therefore lands at 40.0 per 1M — the arithmetic stays consistent with
 * the token pipeline and `inferTier` still classifies them honestly instead of
 * treating every image model as free.
 */

function chat(
  id: string,
  name: string,
  contextWindow: number,
  maxOutput: number,
  inputCostPerMTok: number,
  outputCostPerMTok: number,
  throughputPrior: number,
  features: ChatFeature[] = [],
): CatalogModel {
  return {
    id,
    name,
    modality: 'chat',
    features: ['streaming', ...features],
    contextWindow,
    maxOutput,
    inputCostPerMTok,
    outputCostPerMTok,
    throughputPrior,
  };
}

function embedding(
  id: string,
  name: string,
  contextWindow: number,
  inputCostPerMTok: number,
): CatalogModel {
  return {
    id,
    name,
    modality: 'embeddings',
    features: [],
    contextWindow,
    maxOutput: 0,
    inputCostPerMTok,
    outputCostPerMTok: 0,
    throughputPrior: 0,
  };
}

function image(
  id: string,
  name: string,
  inputCostPerMTok: number,
  outputCostPerMTok: number,
): CatalogModel {
  return {
    id,
    name,
    modality: 'images',
    features: [],
    contextWindow: 4_096,
    maxOutput: 0,
    inputCostPerMTok,
    outputCostPerMTok,
    throughputPrior: 0,
  };
}

function transcription(id: string, name: string): CatalogModel {
  return {
    id,
    name,
    modality: 'audio.transcription',
    features: [],
    contextWindow: 448,
    maxOutput: 448,
    inputCostPerMTok: 0,
    outputCostPerMTok: 0,
    throughputPrior: 0,
  };
}

function freeTier(
  summary: string,
  requestsPerDay: number | null,
  tokensPerMinute: number | null,
  noCardRequired: boolean,
): FreeTier {
  return { summary, requestsPerDay, tokensPerMinute, noCardRequired };
}

